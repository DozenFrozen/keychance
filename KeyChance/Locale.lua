function KC.Lang()
    local pref = KC.db and KC.db.language or "auto"
    if pref == "auto" then return GetLocale() == "ruRU" and "ru" or "en" end
    return pref
end

-- Названия данжей и боссов игра отдаёт на языке клиента; в английском режиме берём английские из данных WCL.
function KC.DungeonName(instanceID, clientName)
    local d = KC.Lang() == "en" and instanceID and KC.Data.dungeons and KC.Data.dungeons[instanceID]
    return d and d.name or clientName
end

function KC.BossName(encounterID, clientName)
    local n = KC.Lang() == "en" and encounterID and KC.Data.bossNames and KC.Data.bossNames[encounterID]
    return n or clientName
end

KC.L = setmetatable({}, {
    __index = function(_, key)
        if KC.Lang() == "en" then return EN[key] or key end
        return key
    end,
})
